#!/usr/bin/env node
// Prints content counts by vertical and status, and regenerates
// docs/content-backlog.md listing every page and its missing data/fields.
const fs = require("fs");
const path = require("path");
const seo = require("../src/lib/verticalSeo");
const services = require("../src/lib/services");

function missingFields(record) {
  const missing = [];
  const c = record.content;
  if (!c) return ["content-file"];
  if (c.status !== "reviewed") missing.push(`status:${c.status || "none"}`);
  if (!c.directAnswer) missing.push("directAnswer");
  if (!c.intro) missing.push("intro");
  if (!c.localInsight) missing.push("localInsight");
  if (!Array.isArray(c.localChecklist) || c.localChecklist.length === 0)
    missing.push("localChecklist");
  if (!Array.isArray(c.faqs) || c.faqs.length === 0) missing.push("faqs");
  if (!c.summary) missing.push("summary");
  for (const f of record.failures) missing.push(f);
  return [...new Set(missing)];
}

function main() {
  const result = seo.computePublished({ includeDrafts: true });
  const { all } = result;

  const byVertical = {};
  const statusOf = (p) => {
    const content = seo.loadContent(p);
    return content ? content.status || "none" : "missing";
  };

  for (const page of all) {
    const v = page.vertical.slug;
    byVertical[v] = byVertical[v] || {};
    const s = statusOf(page);
    byVertical[v][s] = (byVertical[v][s] || 0) + 1;
  }

  console.log("Content status by vertical");
  console.log("--------------------------");
  for (const [v, statuses] of Object.entries(byVertical)) {
    const parts = Object.entries(statuses)
      .map(([s, n]) => `${s}=${n}`)
      .join(", ");
    console.log(`${v}: ${parts}`);
  }

  const serviceEval = services.evaluateServices();
  const serviceStatus = {};
  for (const r of serviceEval) {
    const s = r.content ? r.content.status || "none" : "missing";
    serviceStatus[s] = (serviceStatus[s] || 0) + 1;
  }
  console.log("Service content by status");
  console.log("-------------------------");
  console.log(
    Object.entries(serviceStatus)
      .map(([s, n]) => `${s}=${n}`)
      .join(", ")
  );

  const lines = [];
  lines.push("# Vertical SEO content backlog (generated)");
  lines.push("");
  lines.push("Generated by `scripts/content-status.js`. Do not edit by hand.");
  lines.push("");
  lines.push("| URL | Vertical | Level | Status | Missing / failing |");
  lines.push("| --- | --- | --- | --- | --- |");
  for (const page of all.sort((a, b) =>
    a.urlPath.localeCompare(b.urlPath)
  )) {
    const content = seo.loadContent(page);
    const status = content ? content.status || "none" : "missing";
    const basics = seo.evaluateBasics(page, content);
    const missing = missingFields({ ...page, content, failures: basics.failures });
    lines.push(
      `| ${page.urlPath} | ${page.vertical.slug} | ${page.kind} | ${status} | ${missing.join(", ")} |`
    );
  }
  lines.push("");
  const out = path.join(process.cwd(), "docs", "content-backlog.md");
  fs.writeFileSync(out, lines.join("\n"), "utf8");
  console.log(`\nWrote ${path.relative(process.cwd(), out)}`);
}

main();
